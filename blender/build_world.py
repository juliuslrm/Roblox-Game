"""Assemble the village world from the level plan.

Outputs
  world/world_layout.json      machine readable level description (all transforms)
  world/heightmap.json         terrain height grid + material classes
  world/level_plan.png         2D map of the level
  world/village_world.blend    fully assembled, editable scene (instanced assets)
  exports/glb/terrain/*.glb    terrain chunks, roads, square, water
  exports/library/village_terrain.{glb,fbx}
  roblox/WorldLayout.lua       generated Luau data module (same content as the JSON)
  roblox/WorldHeightmap.lua    generated Luau height map (optional voxel terrain)

    python blender/build_world.py [--no-blend]
"""
import argparse
import json
import math
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import bpy  # noqa: E402

from village import coords, export, luadata, palette, planmap, registry, worldmesh  # noqa: E402
from village import plan as pl  # noqa: E402
from village import scene as sc  # noqa: E402
from village import terrain as tr  # noqa: E402
from village.meshkit import MeshBuilder  # noqa: E402

LAYOUT_VERSION = 1


def build_world_meshes(plan):
    """Returns [(name, MeshBuilder, origin_xy, collision, extra)]."""
    out = []
    chunks = tr.N // tr.CHUNK_CELLS
    for cj in range(chunks):
        for ci in range(chunks):
            mb = MeshBuilder(seed=1000 + cj * 10 + ci)
            ox, oy = worldmesh.terrain_chunk(mb, plan, ci, cj)
            out.append((f"terrain_r{cj}_c{ci}", mb, (ox, oy), "mesh_precise", {"kind": "terrain", "group": "terrain"}))
    for rd in plan.roads:
        mb = MeshBuilder(seed=registry.stable_seed(rd["id"]))
        worldmesh.road_mesh(mb, plan, rd)
        out.append((f"road_{rd['id']}", mb, (0.0, 0.0), "mesh_precise", {"kind": "road", "group": "roads"}))
    mb = MeshBuilder(seed=7)
    worldmesh.plaza_mesh(mb)
    out.append(("plaza_paving", mb, (0.0, 0.0), "mesh_precise", {"kind": "road", "group": "roads"}))
    mb = MeshBuilder(seed=9)
    worldmesh.bank_mesh(mb, plan, skip=[(plan.bridge["x"], plan.bridge["y"], 16.0)])
    out.append(("stream_banks", mb, (0.0, 0.0), "none", {"kind": "decal", "group": "roads"}))
    mb = MeshBuilder(seed=8)
    worldmesh.water_mesh(mb, plan)
    out.append(("water_surface", mb, (0.0, 0.0), "none", {"kind": "water", "group": "water", "transparency": 0.25}))
    return out


def instance_record(uid, asset, group, x, y, z, rot, scale, name=None):
    rec = {
        "id": uid, "asset": asset, "group": group,
        "blender": {"location": [round(x, 3), round(y, 3), round(z, 3)], "rotation_z_deg": round(rot, 2),
                    "scale": scale},
        "roblox": {"position": coords.to_roblox((x, y, z)), "yaw_deg": round(rot, 2), "scale": scale},
    }
    if name:
        rec["name"] = name
    return rec


def polyline_record(poly, every=3):
    idx = list(range(0, len(poly.xy), every))
    if idx[-1] != len(poly.xy) - 1:
        idx.append(len(poly.xy) - 1)
    return [coords.to_roblox((float(poly.xy[i][0]), float(poly.xy[i][1]), float(poly.z[i]))) for i in idx], idx


def write_summary(layout, plan):
    """Human readable digest of the level plan (world/level_summary.md)."""
    assets = layout["assets"]
    lines = ["# Level summary", "",
             "Generated by `blender/build_world.py` from the level plan. Do not edit by hand.", "",
             f"- World: {layout['meta']['world_size']:.0f} x {layout['meta']['world_size']:.0f} studs, "
             f"terrain height {plan.grid.H.min():.1f} .. {plan.grid.H.max():.1f} studs",
             f"- {layout['meta']['counts']['instances']} placed instances of {layout['meta']['counts']['assets']} "
             f"unique meshes, {layout['meta']['counts']['triangles']} triangles in total", "",
             "## Buildings", "",
             "| Name | Asset | Blender x, y, z | Rotation | Roblox position | Triangles |", "|---|---|---|---|---|---|"]
    for i in layout["instances"]:
        if i["group"] != "buildings":
            continue
        b, r = i["blender"], i["roblox"]
        lines.append(f"| {i.get('name', '')} | `{i['asset']}` | {b['location'][0]:.1f}, {b['location'][1]:.1f}, "
                     f"{b['location'][2]:.1f} | {b['rotation_z_deg']:.0f} deg | {r['position'][0]:.1f}, "
                     f"{r['position'][1]:.1f}, {r['position'][2]:.1f} | {assets[i['asset']]['triangles']} |")
    lines += ["", "## Roads", "", "| Name | Id | Kind | Width | Length |", "|---|---|---|---|---|"]
    for rd in plan.roads:
        lines.append(f"| {rd['name']} | `{rd['id']}` | {rd['kind']} | {rd['hw'] * 2:.1f} | {rd['poly'].length:.0f} |")
    lines += ["", "## Instances per group", "", "| Group | Instances | Triangles |", "|---|---|---|"]
    groups = {}
    for i in layout["instances"]:
        g = groups.setdefault(i["group"], [0, 0])
        g[0] += 1
        g[1] += assets[i["asset"]]["triangles"]
    for name, (count, tris) in sorted(groups.items()):
        lines.append(f"| {name} | {count} | {tris} |")
    lines += ["", "## Most used assets", "", "| Asset | Count |", "|---|---|"]
    counts = {}
    for i in layout["instances"]:
        counts[i["asset"]] = counts.get(i["asset"], 0) + 1
    for name, count in sorted(counts.items(), key=lambda kv: -kv[1])[:25]:
        lines.append(f"| `{name}` | {count} |")
    with open(sc.path("world", "level_summary.md"), "w") as fh:
        fh.write("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-blend", action="store_true", help="skip the .blend scene and mesh exports")
    args = ap.parse_args()
    t0 = time.time()
    manifest = json.load(open(sc.path("world", "asset_manifest.json")))["assets"]
    palette.write_texture(sc.TEXTURE_PATH)
    plan = pl.build_plan(manifest)
    print(f"[plan] {len(plan.instances)} instances in {time.time() - t0:.1f}s")

    assets = {k: dict(v) for k, v in manifest.items()}
    instances = []

    # ---------------- world specific meshes
    export.new_scene()
    world_meshes = build_world_meshes(plan)
    world_objs = []
    for name, mb, (ox, oy), collision, extra in world_meshes:
        entry = export.describe(mb, "terrain", "world/village_world.blend", f"exports/glb/terrain/{name}.glb",
                                collision=collision)
        group = extra.pop("group")
        entry.update(extra)
        assets[name] = entry
        instances.append(instance_record(f"{name}#1", name, group, ox, oy, 0.0, 0.0, 1.0))
        if not args.no_blend:
            obj = mb.to_object(name, sc.TEXTURE_PATH)
            export.export_glb([obj], sc.path(entry["glb"]))          # exported at its local origin
            obj.location = (ox, oy, 0.0)
            world_objs.append(obj)
    print(f"[world] {len(world_meshes)} terrain/road meshes, "
          f"{sum(mb.tri_count() for _n, mb, *_ in world_meshes)} tris")

    for inst in plan.instances:
        instances.append(instance_record(inst["uid"], inst["asset"], inst["group"], inst["x"], inst["y"],
                                         inst["z"], inst["rot"], inst["scale"], inst.get("name")))

    used = {i["asset"] for i in instances}
    layout_assets = {k: v for k, v in assets.items() if k in used}

    # ---------------- layout json
    st = plan.stream
    water_pts, idx = polyline_record(st, every=3)
    roads = []
    for rd in plan.roads:
        pts, _ = polyline_record(rd["poly"], every=3)
        roads.append({"id": rd["id"], "name": rd["name"], "kind": rd["kind"], "half_width": rd["hw"],
                      "points_roblox": pts})
    spawn_b = (0.0, -24.0, pl.PLAZA_Z + 0.5)
    layout = {
        "meta": {
            "layout_version": LAYOUT_VERSION,
            "name": "Stylized Village",
            "units": "studs (1 Blender unit = 1 stud)",
            "world_size": tr.WORLD,
            "coordinate_systems": {
                "blender": "right-handed, Z up, X east, Y north",
                "roblox": "right-handed, Y up",
                "blender_to_roblox": "(x, y, z) -> (x, z, -y); rotation around Blender Z by a == rotation "
                                     "around Roblox Y by a  => CFrame.new(pos) * CFrame.Angles(0, rad(a), 0)",
                "asset_origin": "ground contact point of the asset; front (main door) faces Blender -Y = Roblox +Z",
            },
            "texture": "exports/textures/" + palette.TEXTURE_NAME,
            "counts": {"instances": len(instances), "assets": len(layout_assets),
                       "triangles": sum(layout_assets[i["asset"]]["triangles"] for i in instances)},
        },
        # level building plots of the walkable player workshops (see plan.WORKSHOP_PLOTS)
        "workshop_plots": {"half": pl.PLOT_HALF, "plots": [
            {"blender": [p["x"], p["y"], round(float(plan.grid.at(p["x"], p["y"])), 3)],
             "roblox": coords.to_roblox((p["x"], p["y"], round(float(plan.grid.at(p["x"], p["y"])), 3)))}
            for p in plan.plots]},
        "spawn": {"blender": list(spawn_b), "roblox": coords.to_roblox((spawn_b[0], spawn_b[1], spawn_b[2] + 3.0)),
                  "look_at_roblox": coords.to_roblox((0.0, 0.0, 6.0))},
        "lighting": {"clock_time": 15.2, "geographic_latitude": 38.0, "brightness": 2.0,
                     # 2.6 / 0.52 / 0.56 looked overexposed on a phone (player report 2026-11-16)
                     "ambient": [0.27, 0.29, 0.34], "outdoor_ambient": [0.44, 0.47, 0.55],
                     "color_shift_top": [1.0, 0.94, 0.82], "fog_color": [0.78, 0.87, 0.96],
                     "fog_start": 380, "fog_end": 1500},
        "terrain": {"cell": tr.CELL, "vertices_per_side": tr.N + 1, "chunk_cells": tr.CHUNK_CELLS,
                    "origin_blender": [-tr.HALF, -tr.HALF], "heightmap": "world/heightmap.json",
                    "plaza_height": pl.PLAZA_Z},
        "roads": roads,
        "water": {"asset": "water_surface",
                  "points_roblox": water_pts,
                  "half_width": [round(float(st.hw[i]), 2) for i in idx]},
        "assets": layout_assets,
        "instances": instances,
    }
    os.makedirs(sc.path("world"), exist_ok=True)
    with open(sc.path("world", "world_layout.json"), "w") as fh:
        json.dump(layout, fh, indent=1)

    H = plan.grid.H
    with open(sc.path("world", "heightmap.json"), "w") as fh:
        json.dump({"cell": tr.CELL, "vertices_per_side": tr.N + 1, "origin_blender": [-tr.HALF, -tr.HALF],
                   "order": "heights[j][i]: i along +X (east), j along +Y (north); Roblox Z = -Y",
                   "materials_legend": worldmesh.MATERIAL_LEGEND,
                   "heights": [[round(float(v), 2) for v in row] for row in H],
                   "materials": ["".join(str(int(v)) for v in row) for row in plan.material]}, fh)

    # ---------------- Luau data modules
    lua_assets = {}
    for name, a in layout_assets.items():
        br = a["bounds_roblox"]
        e = {"category": a["category"], "collision": a["collision"], "size": br["size"], "center": br["center"],
             "castShadow": a["cast_shadow"]}
        if a.get("transparency"):
            e["transparency"] = a["transparency"]
        if a["colliders"]:
            e["colliders"] = a["colliders"]
        if a["lights"]:
            e["lights"] = a["lights"]
        lua_assets[name] = e
    names = sorted(layout_assets)
    index = {n: i + 1 for i, n in enumerate(names)}
    groups = sorted({i["group"] for i in instances})
    gindex = {g: i + 1 for i, g in enumerate(groups)}
    rows = []
    for i in instances:
        p = i["roblox"]["position"]
        row = [index[i["asset"]], p[0], p[1], p[2], i["roblox"]["yaw_deg"], i["roblox"]["scale"], gindex[i["group"]]]
        if "name" in i:
            row.append(i["name"])
        rows.append("\t\t" + luadata.to_lua(row))
    lua = ["-- AUTO-GENERATED by blender/build_world.py from world/world_layout.json. Do not edit by hand.",
           "-- Positions are Roblox coordinates in studs. Instance rows:",
           "--   { assetIndex, x, y, z, yawDegrees, scale, groupIndex [, displayName] }",
           "return {",
           f"\tlayoutVersion = {LAYOUT_VERSION},",
           f"\tworldSize = {luadata.to_lua(tr.WORLD)},",
           f"\tspawn = {luadata.to_lua(layout['spawn']['roblox'])},",
           f"\tspawnLookAt = {luadata.to_lua(layout['spawn']['look_at_roblox'])},",
           f"\tworkshopPlots = {luadata.to_lua({'half': layout['workshop_plots']['half'], 'plots': [q['roblox'] for q in layout['workshop_plots']['plots']]}, 1, 0)},",
           f"\tlighting = {luadata.to_lua(layout['lighting'], 1, 0)},",
           f"\tassetNames = {luadata.to_lua(names)},",
           f"\tgroupNames = {luadata.to_lua(groups)},",
           "\tassets = {"]
    for name in names:
        lua.append(f"\t\t[{luadata.to_lua(name)}] = {luadata.to_lua(lua_assets[name], 2, 0)},")
    lua += ["\t},", "\tinstances = {", ",\n".join(rows) + ",", "\t},", "}", ""]
    os.makedirs(sc.path("roblox"), exist_ok=True)
    with open(sc.path("roblox", "WorldLayout.lua"), "w") as fh:
        fh.write("\n".join(lua))

    flat = [float(v) for row in H for v in row]
    hm = ["-- AUTO-GENERATED by blender/build_world.py. Height map of the village terrain.",
          "-- heights: 2 characters per vertex, row j (north, Roblox -Z) by column i (east, Roblox +X).",
          "-- value = (index(c1) * 90 + index(c2)) * step - offset   (see TerrainBuilder.lua)",
          "return {",
          f"\tcell = {luadata.to_lua(tr.CELL)},",
          f"\tverticesPerSide = {tr.N + 1},",
          f"\toriginX = {luadata.to_lua(-tr.HALF)},",
          f"\toriginZ = {luadata.to_lua(tr.HALF)},  -- Roblox Z of row j = originZ - j * cell",
          f"\toffset = {luadata.to_lua(luadata.H_OFFSET)},",
          f"\tstep = {luadata.to_lua(luadata.H_STEP)},",
          f"\talphabet = {luadata.to_lua(luadata.ALPHABET)},",
          f"\tmaterialLegend = {luadata.to_lua(worldmesh.MATERIAL_LEGEND)},",
          f"\theights = \"{luadata.encode_heights(flat)}\",",
          f"\tmaterials = \"{''.join(str(int(v)) for row in plan.material for v in row)}\",",
          f"\twater = {luadata.to_lua({'points': water_pts, 'halfWidth': layout['water']['half_width']}, 1, 0)},",
          "}", ""]
    with open(sc.path("roblox", "WorldHeightmap.lua"), "w") as fh:
        fh.write("\n".join(hm))

    planmap.draw(plan, manifest, sc.path("world", "level_plan.png"))
    write_summary(layout, plan)
    print(f"[layout] {len(instances)} instances, {len(layout_assets)} assets, "
          f"{layout['meta']['counts']['triangles']} tris")

    if args.no_blend:
        return

    # ---------------- assembled scene
    scene = bpy.context.scene
    cols = {}

    def collection(name):
        if name not in cols:
            cols[name] = bpy.data.collections.new(name)
            scene.collection.children.link(cols[name])
        return cols[name]

    world_group = {i["asset"]: i["group"] for i in instances}
    for obj in world_objs:
        scene.collection.objects.unlink(obj)
        collection(world_group[obj.name]).objects.link(obj)
    meshes = {}
    for inst in plan.instances:
        a = inst["asset"]
        if a not in meshes:
            meshes[a] = registry.build(a).to_mesh(a, sc.TEXTURE_PATH)
        obj = bpy.data.objects.new(inst["uid"], meshes[a])
        obj.location = (inst["x"], inst["y"], inst["z"])
        obj.rotation_euler = (0.0, 0.0, math.radians(inst["rot"]))
        obj.scale = (inst["scale"],) * 3
        collection(inst["group"]).objects.link(obj)
    export.export_glb(world_objs, sc.path("exports", "library", "village_terrain.glb"))
    export.export_fbx(world_objs, sc.path("exports", "library", "village_terrain.fbx"))
    export.save_blend(sc.path("world", "village_world.blend"))
    print(f"[done] world built in {time.time() - t0:.1f}s")


if __name__ == "__main__":
    main()
