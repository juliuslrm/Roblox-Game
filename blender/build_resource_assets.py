"""Builds the gatherable resource models (one per raw item) - and only those.

    python blender/build_resource_assets.py [--preview]

Outputs: assets/resources/*.blend, exports/glb/resources/*.glb,
exports/library/arcane_resources.{glb,fbx}, world/resource_asset_manifest.json,
roblox/gameplay/server/ResourceArt.lua (bounds of every model in Roblox axes),
optionally previews/assets/resources.png.
Checks while building: every item that a resource node hands out has a model and vice versa, size
limits, triangle budget, back-face audit, glTF structure (same checks as the village assets).
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import bpy  # noqa: E402

import audit_backfaces  # noqa: E402
import validate  # noqa: E402
from village import export, palette, registry  # noqa: E402
from village import scene as sc  # noqa: E402
from village.meshkit import MeshBuilder  # noqa: E402
from village.resources import RESOURCES  # noqa: E402

TRI_BUDGET = 2500
MAX_HALF = 3.2      # studs: a node model stays inside a 6.4 stud square around its origin
MAX_HEIGHT = 5.0


def node_items():
    """Item ids handed out by the resource nodes, read from Locations.lua through a Lua runtime."""
    from lupa import LuaRuntime
    lua = LuaRuntime()
    table = lua.execute(open(sc.path("roblox", "gameplay", "shared", "Locations.lua"), encoding="utf-8").read())
    return {node.item for node in table.nodes.values()}


def build(name):
    mb = MeshBuilder(seed=registry.stable_seed(name))
    RESOURCES[name](mb)
    mb.collision = "none"
    return mb


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", action="store_true")
    args = ap.parse_args()
    palette.write_texture(sc.TEXTURE_PATH)
    problems = []
    wanted = {"res_" + item for item in node_items()}
    if wanted != set(RESOURCES):
        problems.append(f"id mismatch: nodes without model {sorted(wanted - set(RESOURCES))}, "
                        f"models without node {sorted(set(RESOURCES) - wanted)}")
    manifest = {}
    for name in RESOURCES:
        export.new_scene()
        mb = build(name)
        obj = mb.to_object(name, sc.TEXTURE_PATH)
        entry = export.describe(mb, "resources", f"assets/resources/{name}.blend", f"exports/glb/resources/{name}.glb")
        bmin, bmax = mb.bounds()
        if max(-bmin[0], bmax[0], -bmin[1], bmax[1]) > MAX_HALF:
            problems.append(f"{name}: wider than {2 * MAX_HALF} studs ({bmin[0]:.2f}..{bmax[0]:.2f}, {bmin[1]:.2f}..{bmax[1]:.2f})")
        if bmax[2] > MAX_HEIGHT or bmin[2] < -0.35:
            problems.append(f"{name}: height range {bmin[2]:.2f}..{bmax[2]:.2f} outside -0.35..{MAX_HEIGHT}")
        if entry["triangles"] > TRI_BUDGET:
            problems.append(f"{name}: {entry['triangles']} triangles > {TRI_BUDGET}")
        entry["item"] = name[4:]
        export.save_blend(sc.path(entry["blend"]))
        export.export_glb([obj], sc.path(entry["glb"]))
        manifest[name] = entry
    rep = validate.Report()
    validate.TRI_BUDGET["resources"] = TRI_BUDGET
    for name, entry in manifest.items():
        validate.check_asset(rep, name, entry, len(palette.COLORS))
    problems += [f"{sec}: {msg}" for status, sec, msg in rep.rows if status == "FAIL"]
    # back faces
    scene, cam, mat = audit_backfaces.setup()
    tmp = os.path.join(sc.path("world"), "_audit_tmp.png")
    for name in RESOURCES:
        mb = build(name)
        mesh = mb.to_mesh(name, sc.TEXTURE_PATH)
        mesh.materials.clear()
        mesh.materials.append(mat)
        obj = bpy.data.objects.new(name, mesh)
        scene.collection.objects.link(obj)
        back, front, worst = audit_backfaces.count_backfaces(scene, cam, obj, *mb.bounds(), audit_backfaces.VIEWS_ASSET, tmp)
        bpy.data.objects.remove(obj)
        manifest[name]["backface_pixels"] = back
        if back > max(8, front * 1e-4):
            problems.append(f"{name}: {back} back-face pixels (worst view {worst[1]})")
    if os.path.exists(tmp):
        os.remove(tmp)
    # library: all models in a row
    export.new_scene()
    objs, x = [], 0.0
    for name in RESOURCES:
        mb = build(name)
        obj = mb.to_object(name, sc.TEXTURE_PATH)
        bmin, bmax = mb.bounds()
        x -= bmin[0]
        obj.location = (x, 0, 0)
        x += bmax[0] + 3
        objs.append(obj)
    export.export_glb(objs, sc.path("exports", "library", "arcane_resources.glb"))
    export.export_fbx(objs, sc.path("exports", "library", "arcane_resources.fbx"))
    with open(sc.path("world", "resource_asset_manifest.json"), "w") as fh:
        json.dump({"units": "studs", "assets": manifest}, fh, indent=1)
    # bounds for the Roblox adapter (a MeshPart sits at the centre of its bounding box)
    lines = ["-- Generated by blender/build_resource_assets.py. Do not edit.",
             "-- Bounds of the resource models in Roblox axes, relative to the ground point of the node.",
             "return {"]
    for name, entry in manifest.items():
        b = entry["bounds_roblox"]
        lines.append(f"\t{name} = {{ center = {{{b['center'][0]:g}, {b['center'][1]:g}, {b['center'][2]:g}}}, "
                     f"size = {{{b['size'][0]:g}, {b['size'][1]:g}, {b['size'][2]:g}}} }},")
    lines += ["}", ""]
    with open(sc.path("roblox", "gameplay", "server", "ResourceArt.lua"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    tris = [e["triangles"] for e in manifest.values()]
    print(f"resource assets: {len(manifest)} meshes, {min(tris)}-{max(tris)} triangles, {sum(tris)} total")
    for p in problems:
        print("  FAIL", p)
    print(f"resource asset checks: {len(problems)} problems")
    if args.preview:
        import render_previews
        registry.ASSETS.update({n: {"category": "resources", "fn": fn, "dir": "assets/resources", "default_collision": "none"}
                                for n, fn in RESOURCES.items()})
        render_previews.render_sheet(list(RESOURCES), sc.path("previews", "assets", "resources.png"), 5, 9, az=-118, el=24)
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
