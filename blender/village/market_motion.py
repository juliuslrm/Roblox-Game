def sample(track, elapsed):
    t = elapsed % DURATION
    for a, b in zip(track, track[1:]):
        if t <= b[0]:
            u = (1 - math.cos(math.pi * (t - a[0]) / (b[0] - a[0]))) * 0.5
            return tuple(x + u * (y - x) for x, y in zip(a[1:], b[1:]))
    return track[-1][1:]
