MERCHANT_TRIANGLE_BUDGET = 6000


def audit_catalog():
    lua = new_runtime()
    data = lua.globals().loadModule("server/Data")
    layout = lua.execute((ROOT / "roblox/WorldLayout.lua").read_text(encoding="utf-8"))
    ids = lua_list(data.Market.order)
    assert len(ids) == len(set(ids)) == len(market.STYLES) == 5
    anchors = data.Market.anchors(layout)
    assert set(anchors) == set(ids)
    assert len({anchors[key].index for key in ids}) == len(ids)
    nodes = {n.item for n in data.Locations.nodes.values()}
    inputs = {key for recipe in data.Recipes.values() for key in recipe.inputs}
    if any(r.fuelUnits for r in data.Recipes.values()):
        inputs.add("fuel_charcoal")
    base = {item.id for item in data.Items.values() if item.type in ("raw", "fuel")}
    products = {item.id for item in data.Items.values() if item.sellBase > 0}
    intermediates = {item.id for item in data.Items.values() if item.type == "intermediate"}
    outputs = {key for recipe in data.Recipes.values() for key in recipe.outputs}
    assert base <= nodes and base <= inputs and intermediates <= outputs
    listed = set()
    for key in ids:
        a = anchors[key]
        assert math.hypot(a.approachX - a.x, a.approachZ - a.z) > 4.3
        assert math.hypot(a.approachX, a.approachZ) > 17
        for offer in data.Market.merchants[key].offers.values():
            item = data.Items[offer.item]
            assert item and offer.item not in listed and offer.coins > 0 and offer.amount > 0
            assert offer.amount <= item.stackLimit and item.sellBase == 0
            if offer.unlock:
                rule = offer.unlock
                assert rule.research is None or data.Research[rule.research]
                assert rule.quest is None or data.Quests.main[rule.quest]
            if offer.item in nodes:
                def rule_key(rule):
                    return (rule.research, rule.quest) if rule else (None, None)
                assert any(n.item == offer.item and rule_key(n.unlock) == rule_key(offer.unlock)
                           for n in data.Locations.nodes.values())
            listed.add(offer.item)
    assert listed == (base - {"water"}) | {"vial"}
    print(f"[market] {len(ids)} stalls, {len(base)} ground supplies, {len(listed)} offers, "
          f"{len(intermediates)} crafted components and {len(products)} sellable products")
    return data.Market, ids, anchors


def group(target, name):
    result = bpy.data.collections.new(name)
    target.collection.children.link(result)
    return result


def clone(group, source, frame):
    obj = bpy.data.objects.new(source.name + "_preview", source.data)
    group.objects.link(obj)
    obj.matrix_world = frame
    return obj


def actor(group, role, frame):
    name = "merchant_" + role
    rig, _, _, _ = market_rig.create(group, role, registry.stable_seed(name))
    rig.matrix_world = frame


def timeline(target):
    target.render.fps = 24
    target.frame_start, target.frame_end = 1, 24 * market_motion.DURATION + 1
    target.frame_set(1)


def mesh(name, builder, target):
    return builder.to_object(name, scene.TEXTURE_PATH, target)


def write_art(shapes):
    file = ROOT / "roblox/gameplay/server/MarketArt.lua"
    file.write_text("-- Generated by blender/build_market.py.\nreturn "
                    + luadata.to_lua(shapes, inline_depth=2) + "\n", encoding="utf-8")


def render_setup(target, size):
    scene.setup_render(target, size, samples=40)
    target.cycles.use_denoising = False
    target.view_settings.view_transform = "AgX"
    target.render.threads_mode = "FIXED"
    target.render.threads = 8


def lettering(target, name, text, pos, size, color):
    if not bpy.data.materials.get(name):
        mat = bpy.data.materials.new(name)
        mat.diffuse_color = (*color, 1)
        mat.use_nodes = True
        mat.node_tree.nodes.get("Principled BSDF").inputs["Base Color"].default_value = (*color, 1)
    curve = bpy.data.curves.new(text, "FONT")
    curve.body, curve.align_x, curve.size = text, "CENTER", size
    curve.materials.append(bpy.data.materials[name])
    obj = bpy.data.objects.new(text, curve)
    target.objects.link(obj)
    obj.location = pos
    obj.rotation_euler.x = math.radians(90)


def make_lineup(target, catalog, ids):
    timeline(target)
    studio = group(target, "Berufe und Waren")
    positions = ((-8.4, 13.7), (0, 13.7), (8.4, 13.7), (-4.2, -13.7), (4.2, -13.7))
    view_angles = (8, 4, -15, 11, 14)
    for index, (role, (x, y)) in enumerate(zip(ids, positions)):
        spec = catalog.merchants[role]
        actor(studio, role, T(x, y + 0.32, 0.25) @ R("Z", view_angles[index]))
        stand = MeshBuilder(seed=50 + index)
        with stand.at(T(x, y, 0)):
            stand.box(7.65, 4.25, 0.24, "wood_dark", (0, -0.75, 0))
            stand.box(7.55, 0.16, 1.28, market.STYLES[role][0], (0, -2.90, -0.34))
            stand.box(7.62, 0.12, 0.10, "brass", (0, -2.98, -0.37))
            with stand.at(T(0, -1.20, 0.04)):
                market.goods(stand, role, z=0.22)
        mesh("Display_" + role, stand, studio)
        lettering(studio, "Warm Ivory", spec.name, (x, y - 3.12, 0.30), 0.58, (0.94, 0.81, 0.59))
        lettering(studio, "Warm Ivory", spec.trade, (x, y - 3.12, -0.16), 0.36, (0.94, 0.81, 0.59))
    scene.ground_plane(target, size=220, color="stone_warm", z=-0.39)
    render_setup(target, (1460, 1120))
    scene.setup_light(target, sun_az=243, sun_el=53, sun_strength=2.7, sky=(0.76, 0.84, 1.0), sky_strength=0.78)
    cam = scene.add_camera(target, "Händlerübersicht")
    cam.data.type, cam.data.ortho_scale = "ORTHO", 28
    scene.aim(cam, (0.5, -62, 25.8), (0, -1.4, 2.65))
    for line_y in (13.7, -13.7):
        fill = bpy.data.lights.new("Weiches Gesichtslicht", "AREA")
        fill.energy, fill.size = 1650, 12
        fill.color = (0.88, 0.93, 1)
        lamp = bpy.data.objects.new(fill.name, fill)
        target.collection.objects.link(lamp)
        scene.aim(lamp, (2.6, line_y - 11, 6.7), (0, line_y, 4.9))


def market_context(target, layout):
    context = group(target, "Vorhandenes Dorf")
    sources = {}
    for row in layout["instances"]:
        name, kind = row["asset"], row["group"]
        pose = row["blender"]
        x, y, z = pose["location"]
        distance = math.hypot(x, y)
        if kind == "market" or (kind == "terrain" and distance > 148):
            continue
        if kind == "roads" and name not in ("plaza_paving", "road_south_road", "road_north_road", "road_west_road", "road_east_road"):
            continue
        if kind not in ("roads", "terrain") and (name not in registry.ASSETS or distance > 115):
            continue
        if name not in sources:
            if name in registry.ASSETS:
                sources[name] = registry.build(name).to_mesh(name, scene.TEXTURE_PATH)
            else:
                bpy.ops.import_scene.gltf(filepath=str(ROOT / layout["assets"][name]["glb"]))
                imported, = [o for o in bpy.context.selected_objects if o.type == "MESH"]
                sources[name] = imported.data.copy()
                sources[name].transform(imported.matrix_world)
                bpy.data.objects.remove(imported, do_unlink=True)
        obj = bpy.data.objects.new(row.get("name", name), sources[name])
        context.objects.link(obj)
        obj.matrix_world = T(x, y, z) @ R("Z", pose["rotation_z_deg"])
        obj.scale = (pose["scale"],) * 3


def make_plaza(target, layout, ids, anchors, models):
    timeline(target)
    market_context(target, layout)
    vendors = group(target, "Neue Marktstände")
    for role in ids:
        a = anchors[role]
        pivot = T(a.x, -a.z, a.y + 0.34) @ R("Z", a.yaw)
        clone(vendors, models["stall_" + role], pivot)
        actor(vendors, role, pivot @ T(0, 1.6, 0))
    render_setup(target, (1540, 1050))
    scene.setup_light(target, sun_az=251, sun_el=44, sun_strength=3.1, sky_strength=0.8)
    cam = scene.add_camera(target, "Marktplatz")
    cam.data.type, cam.data.ortho_scale = "ORTHO", 96
    scene.aim(cam, (48, -92, 146), (-1, 0, 2))


def arguments():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--no-render", action="store_true")
    if "--" in sys.argv:
        args = sys.argv[sys.argv.index("--") + 1:]
    elif Path(sys.argv[0]).resolve() == Path(__file__).resolve():
        args = sys.argv[1:]
    else:
        args = []
    return parser.parse_args(args)


def check_idle_clip(doc, actors):
    clip, = doc["animations"]
    assert len(doc["skins"]) == actors
    joints = {index for skin in doc["skins"] for index in skin["joints"]}
    assert len(joints) == 8 * actors
    rotating = {channel["target"]["node"] for channel in clip["channels"]
                if channel["target"]["path"] == "rotation"}
    assert len(rotating & joints) >= 7 * actors
    for node in doc["nodes"]:
        if "skin" in node:
            for primitive in doc["meshes"][node["mesh"]]["primitives"]:
                assert {"JOINTS_0", "WEIGHTS_0"} <= primitive["attributes"].keys()
    times = [doc["accessors"][sampler["input"]] for sampler in clip["samplers"]]
    assert all(abs(item["min"][0]) < 0.001 and
               abs(item["max"][0] - market_motion.DURATION) < 0.001 for item in times)


def main():
    args = arguments()
    catalog, ids, anchors = audit_catalog()
    art = export.new_scene()
    art.name = "03 - Exportmodelle"
    library = group(art, "Einzelne Figuren und Stände")
    timeline(art)
    models, shapes, exports, motion = {}, {}, [], {}
    for index, role in enumerate(ids):
        name = "merchant_" + role
        rig, skinned, whole, channels = market_rig.create(
            library, role, registry.stable_seed(name), merged=True)
        bounds = coords.bounds_to_roblox(*whole.bounds())
        assert abs(bounds["min"][1]) < 0.01 and bounds["size"][1] < 7.4
        shapes[name] = {key: bounds[key] for key in ("center", "size")}
        motion[role] = {bone: [(q.x, q.z, -q.y, q.w) for _, q in keys]
                        for bone, keys in channels.items()}
        file = OUT / (name + ".glb")
        art.frame_set(1)
        export.export_glb([rig, *skinned], str(file), animate=True)
        doc, triangles = read_glb(file)
        assert triangles <= MERCHANT_TRIANGLE_BUDGET
        assert any(node["name"] == name and "skin" in node for node in doc["nodes"])
        check_idle_clip(doc, 1)
        print(f"[market] {role}: {triangles} triangles, {bounds['size'][1]} studs high, 7 animated bones")
        rig.location.x = index * 12
        exports.extend([rig, *skinned])

        stall_name = "stall_" + role
        stall = MeshBuilder(seed=registry.stable_seed(stall_name))
        market.stall(stall, role)
        obj = mesh(stall_name, stall, library)
        obj.location = (index * 12, 12, 0)
        models[stall_name] = obj
        exports.append(obj)
        bounds = coords.bounds_to_roblox(*stall.bounds())
        shapes[stall_name] = {key: bounds[key] for key in ("center", "size")}
    combined = OUT / "ArcaneMarket.glb"
    art.frame_set(1)
    export.export_glb(exports, str(combined), animate=True)
    doc, triangles = read_glb(combined)
    check_idle_clip(doc, 5)
    print(f"[market] combined library: {len(doc['meshes'])} meshes, {triangles} triangles")
    write_art(shapes)
    (ROOT / "roblox/gameplay/shared/MarketMotion.lua").write_text(
        "-- Generated by blender/build_market.py.\nreturn "
        + luadata.to_lua({"duration": market_motion.DURATION, "bones": motion}, inline_depth=4) + "\n",
        encoding="utf-8")

    lineup = bpy.data.scenes.new("01 - Händlerübersicht")
    bpy.context.window.scene = lineup
    make_lineup(lineup, catalog, ids)
    plaza = bpy.data.scenes.new("02 - Marktplatz")
    bpy.context.window.scene = plaza
    make_plaza(plaza, json.loads((ROOT / "world/world_layout.json").read_text(encoding="utf-8")),
               ids, anchors, models)

    for image in bpy.data.images:
        if image.source == "FILE" and not image.packed_file:
            image.pack()
    bpy.context.window.scene = lineup
    for screen in bpy.data.screens:
        for area in screen.areas:
            if area.type == "VIEW_3D":
                area.spaces.active.region_3d.view_perspective = "CAMERA"
    bpy.context.preferences.filepaths.save_version = 0
    ASSETS.mkdir(parents=True, exist_ok=True)
    bpy.ops.wm.save_as_mainfile(filepath=str(ASSETS / "ArcaneVillage_Market.blend"), compress=True)
    if not args.no_render:
        for target, filename in ((lineup, "01-haendler.png"), (plaza, "02-marktplatz.png")):
            bpy.context.window.scene = target
            scene.render(target, str(PREVIEWS / filename))


if __name__ == "__main__":
    main()
